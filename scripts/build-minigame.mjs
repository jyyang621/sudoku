import { readFile, writeFile, mkdir, access } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
import vm from 'node:vm';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'wechat-minigame');
const args = process.argv.slice(2);
const check = args.includes('--check');
const appidArgs = args.filter(value => value.startsWith('--appid='));
if (args.some(value => value !== '--check' && !value.startsWith('--appid=')) || appidArgs.length > 1) {
  throw new Error('用法：node scripts/build-minigame.mjs [--appid=wx0123456789abcdef] 或 --check');
}
const appid = appidArgs[0]?.slice('--appid='.length);
if (appid !== undefined && !/^wx[0-9a-fA-F]{16}$/.test(appid)) {
  throw new Error('AppID 格式应为 wx 加 16 位十六进制字符；请勿填写 AppSecret。');
}
if (check && appid !== undefined) throw new Error('--check 不修改配置；请用构建命令设置 AppID。');

const sourcePath = path.join(root, 'js', 'sudoku.js');
const source = (await readFile(sourcePath, 'utf8')).replace(/\r\n/g, '\n');
const exported = [...source.matchAll(/^export\s+(?:const|function)\s+([A-Za-z_$][\w$]*)/gm)]
  .map(match => match[1]);
assert(exported.length > 0, '未找到可转换的数独引擎导出。');
assert.equal(new Set(exported).size, exported.length, '数独引擎存在重复导出。');

// Mini Game JavaScript runtimes need not implement Intl.DateTimeFormat. For
// contemporary daily challenges Beijing calendar time is UTC + 8 year-round.
// Keep this platform adaptation here so the browser engine stays authoritative.
const dailyPattern = /^export function dailySeed\(date = new Date\(\)\) \{[\s\S]*?^\}/m;
assert(dailyPattern.test(source), 'dailySeed 源码格式已变化，请核对小游戏的北京时间适配。');
const portableDailySeed = `export function dailySeed(date = new Date()) {
  const timestamp = Number(date);
  if (!Number.isFinite(timestamp)) throw new RangeError('Invalid time value');
  const china = new Date(timestamp + 8 * 60 * 60 * 1000);
  if (!Number.isFinite(china.getTime())) throw new RangeError('Invalid time value');
  const year = china.getUTCFullYear();
  const month = String(china.getUTCMonth() + 1).padStart(2, '0');
  const day = String(china.getUTCDate()).padStart(2, '0');
  return year + '-' + month + '-' + day;
}`;
const transformed = source.replace(dailyPattern, portableDailySeed)
  .replace(/^export\s+(?=(?:const|function)\s)/gm, '');
assert(!/^\s*(?:import|export)\b/m.test(transformed), '发现不支持的模块语法，请更新构建器。');
const digest = createHash('sha256').update(source).digest('hex');
const engine = `// Generated by scripts/build-minigame.mjs. Do not edit.\n// Source: js/sudoku.js SHA-256 ${digest}\n'use strict';\n\n${transformed.trimEnd()}\n\nmodule.exports = { ${exported.join(', ')} };\n`;
const entry = "// Generated by scripts/build-minigame.mjs. Do not edit.\nrequire('./src/main.js');\n";
const enginePath = path.join(output, 'lib', 'sudoku.js');
const entryPath = path.join(output, 'game.js');
const configPath = path.join(output, 'project.config.json');

async function readConfig() {
  try {
    return JSON.parse(await readFile(configPath, 'utf8'));
  } catch (error) {
    if (error.code === 'ENOENT') return null;
    throw error;
  }
}

if (!check) {
  await mkdir(path.dirname(enginePath), { recursive: true });
  await writeFile(enginePath, engine, 'utf8');
  await writeFile(entryPath, entry, 'utf8');
  const existing = await readConfig();
  const config = existing || {
    description: '数独之间 · 微信小游戏',
    miniprogramRoot: './',
    compileType: 'game',
    appid: 'touristappid',
    projectname: 'sudoku-between',
    setting: { urlCheck: true, es6: true, minified: true },
    simulatorType: 'wechat',
    condition: {},
  };
  if (appid !== undefined) config.appid = appid;
  if (!existing || appid !== undefined) {
    await writeFile(configPath, `${JSON.stringify(config, null, 2)}\n`, 'utf8');
  }
  console.log('已生成 wechat-minigame/lib/sudoku.js 和 game.js。');
  console.log(config.appid === 'touristappid'
    ? '当前为开发导入占位 AppID；正式预览、上传和发布前需要填写自己的小游戏 AppID。'
    : `保留小游戏 AppID：${config.appid}`);
  process.exit(0);
}

assert.equal(await readFile(enginePath, 'utf8'), engine, '小游戏引擎已过期，请先运行 npm run build:wechat。');
assert.equal(await readFile(entryPath, 'utf8'), entry, '小游戏入口已过期，请先运行 npm run build:wechat。');
const config = await readConfig();
assert.equal(config?.compileType, 'game', 'project.config.json 必须使用 compileType: game。');
assert.equal(config?.miniprogramRoot, './', '请以 wechat-minigame 目录为项目根目录。');
assert(config.appid === 'touristappid' || /^wx[0-9a-fA-F]{16}$/.test(config.appid), '小游戏 AppID 格式无效。');
const gameConfig = JSON.parse(await readFile(path.join(output, 'game.json'), 'utf8'));
assert.equal(gameConfig.deviceOrientation, 'portrait');
const packageConfig = JSON.parse(await readFile(path.join(output, 'package.json'), 'utf8'));
assert.equal(packageConfig.type, 'commonjs');
await access(path.join(output, 'src', 'main.js'));

const require = createRequire(import.meta.url);
const native = require(enginePath);
const web = await import(new URL('../js/sudoku.js', import.meta.url));
assert.deepEqual(Object.keys(native).sort(), Object.keys(web).sort(), '转换后导出与网页引擎不一致。');
assert.deepEqual(native.DIFFICULTIES, web.DIFFICULTIES);
let puzzleCount = 0;
for (const setting of web.DIFFICULTIES) {
  for (const seed of ['wechat-smoke', '2026-10-18', '朋友的同一道题']) {
    const expected = web.generatePuzzle(seed, setting.id);
    const actual = native.generatePuzzle(seed, setting.id);
    assert.deepEqual(actual, expected, `${setting.id}/${seed} 生成结果变化。`);
    assert.equal(native.countSolutions(actual.puzzle), 1);
    assert.deepEqual(native.solve(actual.puzzle), web.solve(expected.puzzle));
    assert.deepEqual(native.getAllCandidates(actual.puzzle), web.getAllCandidates(expected.puzzle));
    assert.deepEqual(native.getConflicts(actual.puzzle), web.getConflicts(expected.puzzle));
    assert.equal(native.isComplete(actual.solution), true);
    puzzleCount += 1;
  }
}
const dates = [
  '2024-02-28T15:59:59.999Z', '2024-02-28T16:00:00.000Z',
  '2024-02-29T16:00:00.000Z', '2026-10-17T15:59:59.999Z',
  '2026-10-17T16:00:00.000Z', '2026-12-31T16:00:00.000Z',
];
for (const iso of dates) {
  const date = new Date(iso);
  assert.equal(native.dailySeed(date), web.dailySeed(date), `北京时间日期不一致：${iso}`);
}
assert.equal(native.dailySeed(new Date('2026-10-17T16:00:00Z')), '2026-10-18');
assert.throws(() => native.dailySeed(new Date(NaN)), RangeError);
// Confirm the generated engine has no Intl dependency at runtime.
const context = { module: { exports: {} }, Intl: undefined };
vm.runInNewContext(engine, context, { filename: enginePath });
assert.equal(context.module.exports.dailySeed(new Date('2026-12-31T16:00:00Z')), '2027-01-01');
new vm.Script(await readFile(path.join(output, 'src', 'main.js'), 'utf8'), { filename: 'src/main.js' });
console.log(`微信小游戏构建检查通过：${puzzleCount} 道跨平台同题、唯一解、候选数、${dates.length} 个日期边界与配置。`);
